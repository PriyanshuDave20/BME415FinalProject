def append_records(path, records):
    with open(path, 'a') as f:
        for rec in records:
            f.write(rec['header'] + '\n')
            seq = rec['seq']

            for i in range(0, len(seq), 60):
                f.write(seq[i:i + 60] + '\n')
    print('appended %d record(s) to %s' % (len(records), path))

